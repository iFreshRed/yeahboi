					<p>Choose Register Organization and submit your organization's information for review.</p>
				</details>
				<details>
					<summary>How can my organization post a volunteer opportunity?</summary>
					<p>After your organization is approved, its management area is where you can publish and manage volunteer opportunities.</p>
				</details>
				<details>
					<summary>How do we verify volunteer hours?</summary>
					<p>After an activity, the organization can confirm attendance and record the hours completed by each volunteer.</p>
				</details>
				<details>
					<summary>How can I contact HelpHive for assistance?</summary>
