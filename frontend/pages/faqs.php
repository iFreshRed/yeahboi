				<h2 id="volunteers-title">For Volunteers</h2>
				<details>
					<summary>How do I find volunteer opportunities?</summary>
					<p>Browse the Search Opportunities page and use the available filters to find activities by location, cause, duration, and interests.</p>
				</details>
				<details>
					<summary>How do I register for a volunteer activity?</summary>
					<p>Choose an opportunity, review its details, and use its registration option. Registration availability depends on the opportunity and your account status.</p>
				</details>
				<details>
					<summary>How can I track my volunteer hours?</summary>
					<p>Completed hours appear in your profile after the organizing team verifies your attendance and records the hours.</p>
				</details>
				<details>
					<summary>What if my volunteer hours are incorrect?</summary>
					<p>Contact the organization that hosted the activity and request a correction to your recorded hours.</p>
				</details>
			</section>

