		<h1>Terms of Service</h1>
		<p>These draft terms describe the intended use of HelpHive as a community platform connecting volunteers and organizations. They should be reviewed and finalized before the service is launched.</p>

		<h2>Using HelpHive</h2>
		<p>Use the platform respectfully and provide accurate information when creating an account, registering an organization, or sharing an opportunity.</p>

		<h2>Opportunities and participation</h2>
		<p>Organizations provide the details of their activities. Volunteers should review the requirements, location, schedule, and safety information before registering or attending.</p>

		<h2>Organization information</h2>
		<p>Organization profiles and opportunities are subject to review. A submitted profile is not considered verified until the review process is complete.</p>

		<h2>Volunteer hours</h2>
		<p>Attendance and hours are recorded and verified by the organization responsible for an activity. HelpHive does not independently certify hours.</p>

		<h2>Availability and updates</h2>
		<p>Platform features and information may change as HelpHive develops. These draft terms need final review to define service availability and update procedures.</p>

